"""Mode Share Estimator - scoring parameter calibration for MATSim experiments.

Two modes of operation:

  (a) Cold start (no --experiment-dir): "current" parameter values are read
      from matsim/configs/basic/config_full.xml (the documented MATSim defaults:
      pt.constant=0.0, walk.constant=0.0, waitingPt=-6.0). The recommended
      values come from an ACS-share tier table only as a seed for the very
      first run, and only if they differ materially from the MATSim defaults.

  (b) Iterative calibration (--experiment-dir <path>): reads the experiment's
      modestats.csv (realised mode shares at the final iteration) and the
      experiment's config.xml (the scoring params it actually ran with).
      Applies a clamped log-ratio update toward ACS targets:

          Delta = clip(0.5 * ln(ACS_share / sim_share), -1.0, +1.0)

      This is the standard alternative-specific-constant (ASC) update from
      discrete choice calibration. Delta is computed independently for
      pt.constant (toward ACS transit share) and walk.constant (toward ACS
      walk share). waitingPt is left at whatever the experiment used -
      tuning waitingPt iteratively is rarely the right lever.

  The transitRouter block (searchRadius, extensionRadius,
  maxBeelineWalkConnectionDistance, directWalkFactor) is updated via a
  separate tier-bump rule (see TRANSIT_ROUTER_TIERS): cold start seeds from
  ACS transit share, feedback bumps +/-1 tier when the realised PT share is
  outside [ROUTER_FEEDBACK_UNDER, ROUTER_FEEDBACK_OVER] of the ACS target.

Outputs:
    config/<region>/config_<stem>_estimated.json (single source of truth)
    logs/mode_share_estimator_YYYYMMDD_HHMMSS.log

At experiment time the MATSim config.xml is generated by ConfigManager from
the base template (matsim/configs/<mode>/config.xml) overlaid with the JSON's
matsim.configurable_params - this estimator does not write any XML.

Usage:
    # Cold start
    python estimators/mode_share_estimator.py config/USA/Birmingham_AL/config.json

    # Iterative calibration
    python estimators/mode_share_estimator.py config/USA/Birmingham_AL/config.json \
        --experiment-dir /path/to/experiments/experiment_20260511_140420
"""

