# ---------------------------------------------------------------------------
# Tunables
# ---------------------------------------------------------------------------
# Standard discrete-choice ASC update: Delta = LOG_RATIO_GAIN * ln(target / sim),
# clamped to +/-MAX_STEP so one outlier iteration can't swing constants wildly.
LOG_RATIO_GAIN = 0.5
MAX_STEP       = 1.0

# Don't recommend a change smaller than this - within numerical noise of MATSim.
MIN_REPORT_DELTA = 0.05

# Floor on simulated shares to avoid ln(0) when a mode collapses entirely.
SIM_SHARE_FLOOR = 1e-4  # 0.01% - well below any ACS commute target.

# ---------------------------------------------------------------------------
# Cold-start tier table (only used when --experiment-dir is NOT provided)
# ---------------------------------------------------------------------------
# Each tier sets three MATSim scoring parameters:
#   pt.constant   - alternative-specific constant for PT mode choice
#   waitingPt     - disutility per hour of waiting at PT stops (util/hr)
#   walk.constant - alternative-specific constant for walk mode choice
#
# These are *seed* values for the very first run in a region. Once an
# experiment has been completed, the log-ratio update (Option 3) takes over
# and corrects from the realised shares - the tier table is no longer the
# target. For near-zero ACS regions the seed deliberately stays close to
# MATSim defaults (0.0, 0.0, -6.0) rather than baking in heavy a-priori
# penalties; the empirical correction does the work.

SCORING_TIERS: List[Tuple[float, Dict[str, float]]] = [
    # (min_transit_share, params)
    (0.30, {"pt.constant": 1.5,  "waitingPt": -1.0, "walk.constant": -1.5}),
    (0.10, {"pt.constant": 0.5,  "waitingPt": -1.5, "walk.constant": -2.0}),
    (0.05, {"pt.constant": 0.0,  "waitingPt": -2.0, "walk.constant": -2.5}),
    (0.01, {"pt.constant": 0.0,  "waitingPt": -3.0, "walk.constant": -1.0}),
    (0.00, {"pt.constant": 0.0,  "waitingPt": -3.0, "walk.constant": -1.0}),
]


# ---------------------------------------------------------------------------
# Transit router tier table (cold-start) + feedback rule
# ---------------------------------------------------------------------------
# These four params shape the PT *choice set*, not the utility:
#   searchRadius                     - radius around origin/dest to find stops
#   extensionRadius                  - growth step if no stop is found in radius
#   maxBeelineWalkConnectionDistance - max stop-to-stop / activity-to-stop walk
#   directWalkFactor                 - pt-vs-walk comparison threshold; the
#                                      router returns a direct walk whenever
#                                      direct_walk_time <= factor * pt_time
#
# Memory/CPU note: maxBeelineWalkConnectionDistance is the dangerous one.
# Transit-router graph cost scales ~O(N stops x density x radius^2). The 400m
# ceiling at the top tier matches the textbook "1/4 mile" walk-access standard
# without crossing into ranges that have caused OOM on Hermes for dense
# networks (Chicago, NYC) in prior runs.
#
# additionalTransferTime is intentionally NOT in this table — it is a
# behavior-realism knob, not a calibration lever for mode share.

TRANSIT_ROUTER_TIERS: List[Tuple[float, Dict[str, float]]] = [
    # (min_transit_share, params)
    (0.30, {"searchRadius": 1500.0, "extensionRadius": 300.0,
            "maxBeelineWalkConnectionDistance": 400.0, "directWalkFactor": 2.0}),
    (0.10, {"searchRadius": 1200.0, "extensionRadius": 250.0,
            "maxBeelineWalkConnectionDistance": 350.0, "directWalkFactor": 1.8}),
    (0.05, {"searchRadius": 1000.0, "extensionRadius": 200.0,
            "maxBeelineWalkConnectionDistance": 300.0, "directWalkFactor": 1.5}),
    (0.00, {"searchRadius": 1000.0, "extensionRadius": 200.0,
            "maxBeelineWalkConnectionDistance": 250.0, "directWalkFactor": 1.3}),
]

TRANSIT_ROUTER_PARAMS = (
    "searchRadius",
    "extensionRadius",
    "maxBeelineWalkConnectionDistance",
    "directWalkFactor",
)

# MATSim documented defaults (used as the "current" baseline when the
# experiment's config.xml has no transitRouter block, e.g. very first run).
_TRANSIT_ROUTER_DEFAULTS_FALLBACK = {
    "searchRadius":                     1000.0,
    "extensionRadius":                  200.0,
    "maxBeelineWalkConnectionDistance": 100.0,
    "directWalkFactor":                 1.0,
}

# Feedback rule thresholds: if sim_pt / acs_pt is below UNDER or above OVER,
# bump router params one tier (toward more / less PT availability). Otherwise
# leave them alone and let the scoring constants do the fine-grained work.
ROUTER_FEEDBACK_UNDER = 0.7   # sim < 70% of target -> bump up one tier
ROUTER_FEEDBACK_OVER  = 1.3   # sim > 130% of target -> bump down one tier


# ---------------------------------------------------------------------------
# Tier lookup (cold-start only)
# ---------------------------------------------------------------------------

def _select_tier(transit_share: float) -> Tuple[Dict[str, float], str]:
    for min_share, params in SCORING_TIERS:
        if transit_share >= min_share:
            if min_share == 0.30:
                label = f"NYC-class (>{min_share:.0%})"
            elif min_share == 0.10:
                label = f"high-transit ({min_share:.0%}-30%)"
            elif min_share == 0.05:
                label = f"moderate-transit ({min_share:.0%}-10%)"
            elif min_share == 0.01:
                label = f"low-transit ({min_share:.0%}-5%)"
            else:
                label = "near-zero transit (under 1%)"
            return params, label
    return SCORING_TIERS[-1][1], "near-zero transit (under 1%)"


def _select_router_tier(transit_share: float) -> Tuple[int, Dict[str, float], str]:
    """Return (tier_index, params, label) for the matching transit-router tier.

    tier_index = 0 is the most pt-aggressive (NYC-class), len-1 is the most
    conservative (low-transit). The index is what the feedback rule increments
    or decrements when bumping tiers.
    """
    for idx, (min_share, params) in enumerate(TRANSIT_ROUTER_TIERS):
        if transit_share >= min_share:
            if min_share == 0.30:
                label = f"very-high transit (>={min_share:.0%}) — NYC-class"
            elif min_share == 0.10:
                label = f"high transit ({min_share:.0%}-30%)"
            elif min_share == 0.05:
                label = f"moderate transit ({min_share:.0%}-10%)"
            else:
                label = f"low transit (<{TRANSIT_ROUTER_TIERS[-2][0]:.0%})"
            return idx, params, label
    last = len(TRANSIT_ROUTER_TIERS) - 1
    return last, TRANSIT_ROUTER_TIERS[last][1], "low transit (<5%)"


def _router_params_at_tier(idx: int) -> Dict[str, float]:
    """Clamp idx to a valid tier and return that tier's router params."""
    idx = max(0, min(idx, len(TRANSIT_ROUTER_TIERS) - 1))
    return dict(TRANSIT_ROUTER_TIERS[idx][1])


def _router_feedback_direction(sim_pt: float, acs_pt: float) -> int:
    """Return -1 (bump up tier), +1 (bump down), or 0 (hold).

    Bumping "up a tier" means moving to a lower index in TRANSIT_ROUTER_TIERS
    (= more aggressive PT availability), hence -1. "Down a tier" is the
    opposite direction. Returns 0 inside the dead-band so the router params
    don't oscillate every iteration — let the scoring constants do the fine
    correction.
    """
    if acs_pt <= SIM_SHARE_FLOOR:
        return 0
    ratio = max(sim_pt, SIM_SHARE_FLOOR) / acs_pt
    if ratio < ROUTER_FEEDBACK_UNDER:
        return -1
    if ratio > ROUTER_FEEDBACK_OVER:
        return +1
    return 0


